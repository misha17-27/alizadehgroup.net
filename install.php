<?php
/**
 * One-time installer: writes app/config.php, creates tables, imports the initial content
 * and creates the first administrator. Locked as soon as app/config.php exists.
 */
declare(strict_types=1);

require __DIR__ . '/app/bootstrap.php';
require APP_DIR . '/database/migrate.php';

start_session();
send_security_headers();
header('X-Robots-Tag: noindex');

$installed = is_installed();
$errors = [];
$done = false;
$v = [
    'driver' => 'mysql', 'host' => 'localhost', 'port' => '3306', 'name' => '', 'user' => '', 'pass' => '',
    'admin_name' => '', 'admin_email' => '', 'admin_pass' => '',
];

if (!$installed && is_post()) {
    foreach ($v as $k => $_) $v[$k] = trim((string)($_POST[$k] ?? ''));
    $v['admin_pass'] = (string)($_POST['admin_pass'] ?? '');
    $v['pass'] = (string)($_POST['pass'] ?? '');
    if (!csrf_ok()) $errors[] = 'Sessiya bitib, səhifəni yeniləyin. / Session expired, reload the page.';
    if (!in_array($v['driver'], ['mysql', 'sqlite'], true)) $errors[] = 'DB driver';
    if ($v['driver'] === 'mysql' && ($v['name'] === '' || $v['user'] === '')) $errors[] = 'MySQL: verilənlər bazası və istifadəçi adı tələb olunur. / Database name and user are required.';
    if (!filter_var($v['admin_email'], FILTER_VALIDATE_EMAIL)) $errors[] = 'Admin e-poçtu düzgün deyil. / Invalid admin e-mail.';
    if (mb_strlen($v['admin_pass']) < 8) $errors[] = 'Parol ən azı 8 simvol olmalıdır. / Password must be at least 8 characters.';
    if ($v['driver'] === 'sqlite' && !extension_loaded('pdo_sqlite')) $errors[] = 'pdo_sqlite extension is not available on this server — choose MySQL.';
    if ($v['driver'] === 'mysql' && !extension_loaded('pdo_mysql')) $errors[] = 'pdo_mysql extension is not available.';
    if (!is_writable(APP_DIR)) $errors[] = 'app/ qovluğuna yazmaq mümkün deyil. / app/ is not writable.';

    if (!$errors) {
        $db = $v['driver'] === 'sqlite'
            ? ['driver' => 'sqlite', 'path' => STORAGE_DIR . '/database.sqlite']
            : ['driver' => 'mysql', 'host' => $v['host'] ?: 'localhost', 'port' => (int)($v['port'] ?: 3306), 'name' => $v['name'], 'user' => $v['user'], 'pass' => $v['pass']];
        try {
            if ($db['driver'] === 'sqlite') {
                $pdo = new PDO('sqlite:' . $db['path'], null, null, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
            } else {
                $pdo = new PDO(sprintf('mysql:host=%s;port=%d;dbname=%s;charset=utf8mb4', $db['host'], $db['port'], $db['name']), $db['user'], $db['pass'], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
            }
            $pdo = null;
        } catch (Throwable $e) {
            $errors[] = 'Bazaya qoşulmaq alınmadı / Could not connect: ' . $e->getMessage();
        }
    }

    if (!$errors) {
        $cfg = ['db' => $db, 'base_path' => null];
        $php = "<?php\n// Generated by install.php on " . date('Y-m-d H:i') . ". Not tracked by git.\nreturn " . var_export($cfg, true) . ";\n";
        if (@file_put_contents(CONFIG_FILE, $php, LOCK_EX) === false) {
            $errors[] = 'app/config.php yazıla bilmədi. / Could not write app/config.php.';
        } else {
            @chmod(CONFIG_FILE, 0640);
            config_all($cfg);
            try {
                migrate();
                seed();
                if (!val('SELECT COUNT(*) FROM users')) {
                    insert('users', ['name' => $v['admin_name'] ?: 'Admin', 'email' => mb_strtolower($v['admin_email']),
                        'pass' => password_hash($v['admin_pass'], PASSWORD_DEFAULT), 'role' => 'admin', 'ui_lang' => 'az',
                        'active' => 1, 'created_at' => now()]);
                }
                $done = true;
            } catch (Throwable $e) {
                @unlink(CONFIG_FILE);
                $errors[] = 'Quraşdırma xətası / Install error: ' . $e->getMessage();
            }
        }
    }
}
